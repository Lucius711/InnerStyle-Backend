package com.innerstyle.meshy.repository;

import com.innerstyle.meshy.entity.MeshyTask;
import com.innerstyle.meshy.entity.enums.MeshyTaskStatus;
import com.innerstyle.meshy.entity.enums.MeshyTaskType;
import jakarta.persistence.LockModeType;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.Lock;
import org.springframework.data.jpa.repository.Query;
import org.springframework.data.repository.query.Param;
import org.springframework.stereotype.Repository;

import java.util.List;
import java.util.Optional;
import java.util.UUID;

@Repository
public interface MeshyTaskRepository extends JpaRepository<MeshyTask, UUID> {

    Optional<MeshyTask> findByMeshyTaskId(String meshyTaskId);

    /** Latest live child of a given type (e.g. an existing RIG of a model) — lets us reuse it instead of paying again. */
    Optional<MeshyTask> findFirstByParentIdAndTaskTypeAndStatusInAndDeletedAtIsNullOrderByCreatedAtDesc(
            UUID parentId, MeshyTaskType taskType, java.util.Collection<MeshyTaskStatus> statuses);

    Page<MeshyTask> findByStatus(MeshyTaskStatus status, Pageable pageable);

    /** A user's own tasks (the private library) — includes legacy rows with no owner.
     *  Excludes soft-deleted and EXPIRED tasks. */
    @Query("SELECT t FROM MeshyTask t WHERE (t.userId = :userId OR t.userId IS NULL) AND t.deletedAt IS NULL AND t.status <> 'EXPIRED'")
    Page<MeshyTask> findByUserIdOrLegacy(@Param("userId") UUID userId, Pageable pageable);

    @Query("SELECT t FROM MeshyTask t WHERE (t.userId = :userId OR t.userId IS NULL) AND t.deletedAt IS NULL AND t.status <> 'EXPIRED' AND t.status = :status")
    Page<MeshyTask> findByUserIdOrLegacyAndStatus(@Param("userId") UUID userId,
                                                   @Param("status") MeshyTaskStatus status,
                                                   Pageable pageable);

    /** Tasks expiring within the next N days (for the "expiring soon" banner). */
    @Query("SELECT t FROM MeshyTask t WHERE (t.userId = :userId OR t.userId IS NULL) AND t.deletedAt IS NULL AND t.status = 'SUCCEEDED' AND t.expiresAt IS NOT NULL AND t.expiresAt < :threshold")
    List<MeshyTask> findExpiringSoon(@Param("userId") UUID userId, @Param("threshold") java.time.Instant threshold);

    /** Non-terminal tasks for the polling fallback to reconcile. */
    @Query("SELECT t FROM MeshyTask t WHERE t.status IN :statuses ORDER BY t.updatedAt ASC")
    List<MeshyTask> findActive(@Param("statuses") List<MeshyTaskStatus> statuses, Pageable pageable);

    /** R2 backfill candidates: finished, not deleted, generated by Meshy (not user uploads). */
    @Query("SELECT t.id FROM MeshyTask t WHERE t.status = 'SUCCEEDED' AND t.deletedAt IS NULL"
            + " AND t.taskType <> 'UPLOADED' ORDER BY t.createdAt DESC")
    List<UUID> findR2BackfillCandidates();

    /** Admin model stats: one row per task type. */
    interface TypeCount {
        MeshyTaskType getTaskType();
        Long getTotal();
    }

    /** Admin model stats: one row per (account, task type). */
    interface AccountTypeCount {
        UUID getUserId();
        String getEmail();
        String getFullName();
        MeshyTaskType getTaskType();
        Long getTotal();
        java.time.Instant getLastCreatedAt();
    }

    @Query("SELECT t.taskType AS taskType, COUNT(t) AS total FROM MeshyTask t"
            + " WHERE t.taskType IN :types AND t.status IN :statuses GROUP BY t.taskType")
    List<TypeCount> countByType(@Param("types") java.util.Collection<MeshyTaskType> types,
                                @Param("statuses") java.util.Collection<MeshyTaskStatus> statuses);

    @Query("SELECT u.id AS userId, u.email AS email, u.fullName AS fullName, t.taskType AS taskType,"
            + " COUNT(t) AS total, MAX(t.createdAt) AS lastCreatedAt"
            + " FROM MeshyTask t JOIN User u ON u.id = t.userId"
            + " WHERE t.taskType IN :types AND t.status IN :statuses"
            + " GROUP BY u.id, u.email, u.fullName, t.taskType")
    List<AccountTypeCount> countByAccountAndType(@Param("types") java.util.Collection<MeshyTaskType> types,
                                                 @Param("statuses") java.util.Collection<MeshyTaskStatus> statuses);

    /** Whether a prototype has a build in one of these states (e.g. a failed one, for FREE billing). */
    boolean existsByParentIdAndTaskTypeAndStatusIn(UUID parentId, MeshyTaskType taskType,
            List<MeshyTaskStatus> statuses);

    /** A prototype's running/finished build, reused instead of starting (and billing) a second one. */
    Optional<MeshyTask> findFirstByParentIdAndTaskTypeAndStatusIn(UUID parentId, MeshyTaskType taskType,
            List<MeshyTaskStatus> statuses);

    /** Row lock that serializes the browser's and the server's figurine build for one prototype. */
    @Lock(LockModeType.PESSIMISTIC_WRITE)
    @Query("SELECT t FROM MeshyTask t WHERE t.id = :id")
    Optional<MeshyTask> findByIdForUpdate(@Param("id") UUID id);
}
